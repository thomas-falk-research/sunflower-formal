/// `i -> i + 1 mod n`.
pub fn cyclic_gen(n: u32) -> Perm {
    (0..n).map(|i| (i + 1) % n).collect()
}

/// `i -> -i mod n`.
pub fn reflect_gen(n: u32) -> Perm {
    (0..n).map(|i| (n - i) % n).collect()
}

/// `i -> a*i mod p` on `[p]`, fixing 0. Only a permutation when
/// `gcd(a,p) = 1`.
pub fn mult_gen(p: u32, a: u32) -> Perm {
    (0..p).map(|i| (i * a) % p).collect()
}

/// The block-permutation generators of `Sym(k) wr Sym(t)` acting on
/// `t` blocks of `k` points: the cycle inside block 0 and the swap of
/// blocks 0 and 1, plus the cycle of all blocks.
pub fn block_gens(blocks: u32, size: u32) -> Vec<Perm> {
    let n = blocks * size;
    // cycle inside block 0
    let inner: Perm = (0..n)
        .map(|i| if i < size { (i + 1) % size } else { i })
        .collect();
    // cycle the blocks
    let outer: Perm = (0..n)
        .map(|i| {
            let (blk, off) = (i / size, i % size);
            ((blk + 1) % blocks) * size + off
        })
        .collect();
    // swap blocks 0 and 1
    let swap: Perm = (0..n)
        .map(|i| {
            let (blk, off) = (i / size, i % size);
            match blk {
                0 => size + off,
                1 => off,
                _ => i,
            }
        })
        .collect();
    vec![inner, outer, swap]
}

/// `PGL(2,q)` on the projective line `P^1(F_q)`, `q` prime: points
/// `0..q-1` are `F_q` and point `q` is infinity. Generated by
/// `x -> x+1`, `x -> a x` for a primitive root `a`, and `x -> -1/x`.
/// `PSL(2,q)` is the same with `a` replaced by `a^2`.
pub fn pgl2_gens(q: u32, primitive: u32, projective_special: bool) -> Vec<Perm> {
    let n = q + 1;
    let inf = q;
    let translate: Perm = (0..n).map(|i| if i == inf { inf } else { (i + 1) % q }).collect();
    let a = if projective_special {
        (primitive * primitive) % q
    } else {
        primitive
    };
    let scale: Perm = (0..n).map(|i| if i == inf { inf } else { (i * a) % q }).collect();
    let invert: Perm = (0..n)
        .map(|i| {
            if i == inf {
                0
            } else if i == 0 {
                inf
            } else {
                // -1/i mod q
                let mut inv = 1;
                while (i * inv) % q != 1 {
                    inv += 1;
                }
                (q - inv) % q
            }
        })
        .collect();
    vec![translate, scale, invert]
}

/// `C_k wr C_t`: the wreath product of two cyclic groups acting on `t`
/// blocks of `k` points — order `k^t * t`. The full `Sym(k) wr Sym(t)`
/// is the 300-family's own symmetry and is far too large to prescribe
/// (order `720^3 * 6` at `(k,t) = (6,3)`); this is the natural small
/// subgroup with the same block structure.
pub fn cyclic_wreath_gens(blocks: u32, size: u32) -> Vec<Perm> {
    let n = blocks * size;
    let inner: Perm = (0..n)
        .map(|i| if i < size { (i + 1) % size } else { i })
        .collect();
    let outer: Perm = (0..n)
        .map(|i| {
            let (blk, off) = (i / size, i % size);
            ((blk + 1) % blocks) * size + off
        })
        .collect();
    vec![inner, outer]
}

/// `C_a x C_b` acting on an `a` by `b` grid of `a*b` points.
pub fn grid_gens(a: u32, b: u32) -> Vec<Perm> {
    let n = a * b;
    let rows: Perm = (0..n).map(|i| ((i / b + 1) % a) * b + i % b).collect();
    let cols: Perm = (0..n).map(|i| (i / b) * b + (i % b + 1) % b).collect();
    vec![rows, cols]
}

fn is_prime(p: u32) -> bool {
    p >= 2 && (2..p).take_while(|d| d * d <= p).all(|d| p % d != 0)
}

fn primitive_root(p: u32) -> u32 {
    for a in 2..p {
        let mut x = a % p;
        let mut k = 1;
        while x != 1 {
            x = x * a % p;
            k += 1;
        }
        if k == p - 1 {
            return a;
        }
    }
    1
}

/// A list of groups worth prescribing on `[n]`, as `(name, generators)`.
///
/// Chosen for *many orbits of moderate size*: the whole point of a
/// prescribed group is that a family which is a union of a few orbits is
/// found in a search over a few hundred integers rather than over
/// `C(n,b)` booleans. Very large groups leave too few orbits to reach a
/// target; very small ones leave too many to search.
pub fn standard_groups(n: u32) -> Vec<(String, Vec<Perm>)> {
    let mut out: Vec<(String, Vec<Perm>)> = Vec::new();
    out.push((format!("C_{n}"), vec![cyclic_gen(n)]));
    out.push((format!("D_{n}"), vec![cyclic_gen(n), reflect_gen(n)]));

    // Products of cyclic groups on a grid, and the cyclic wreath with
    // the same block structure.
    for a in 2..n {
        if n % a != 0 {
            continue;
        }
        let b = n / a;
        if a <= b {
            out.push((format!("C_{a} x C_{b} (grid)"), grid_gens(a, b)));
        }
        if a >= 2 && b >= 2 {
            out.push((format!("C_{b} wr C_{a} (blocks)"), cyclic_wreath_gens(a, b)));
        }
    }

    // Affine groups on a prime ground set: C_p semidirect C_k for every
    // k dividing p-1.
    if is_prime(n) {
        let g = primitive_root(n);
        let mut k = 2;
        while k <= n - 1 {
            if (n - 1) % k == 0 {
                let a = {
                    // an element of order k: g^((p-1)/k)
                    let e = (n - 1) / k;
                    let mut x = 1u32;
                    for _ in 0..e {
                        x = x * g % n;
                    }
                    x
                };
                out.push((
                    format!("C_{n} : C_{k} (affine)"),
                    vec![cyclic_gen(n), mult_gen(n, a)],
                ));
            }
            k += 1;
        }
    }

    // Projective groups when n = q + 1 with q prime.
    if n >= 3 && is_prime(n - 1) {
        let q = n - 1;
        let g = primitive_root(q);
        out.push((format!("PSL(2,{q})"), pgl2_gens(q, g, true)));
        out.push((format!("PGL(2,{q})"), pgl2_gens(q, g, false)));
    }
    out
}

