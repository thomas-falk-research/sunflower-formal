//! Kramer–Mesner: search for a record family under a prescribed
//! automorphism group.
//!
//! `docs/roadmap.md` §12 says the record at `b = 6` falls at 317 members
//! and the Abbott–Hanson–Sauer substitution gives 300. `extend.rs` shows
//! the 300-family cannot be extended — on any ground set, and even
//! ignoring sunflower-freeness — so a 317-member family, if one exists,
//! has different symmetry. The 300-family's own group has order
//! `6 * 60^3 = 1296000`; the standard move when a highly symmetric object
//! caps out is to prescribe a *smaller* group and search the orbits.
//!
//! That is Kramer–Mesner, and it is how most record designs are found.
//! The reduction is the point: with a group `G` of order `|G|` prescribed
//! on `[g]`, a `G`-invariant family is a union of `G`-orbits on
//! `b`-subsets, so `C(18,6) = 18564` booleans become a few hundred
//! integers.
//!
//! ## Why this is a backtracking search and not an ILP
//!
//! In the classical setting the constraint is linear (every `t`-set
//! covered `lambda` times) and the orbit reduction produces an integer
//! program. Here the constraint is **ternary and negative** — no three
//! members may form a sunflower — so the orbit-level formulation is a
//! constraint satisfaction problem, not a covering problem. Writing it
//! as an ILP or a SAT instance would need one clause per sunflower
//! triple, and at `(b,g) = (6,18)` there are `C(18564,3) ~ 1e12` triples
//! to test before the first clause is written.
//!
//! So the orbits are searched directly, and the ternary condition is
//! checked *incrementally*, which is what makes it affordable:
//!
//! ```text
//!   A, B, x is a sunflower   iff   A ∩ B ⊆ x   and   x ∩ (A △ B) = ∅
//! ```
//!
//! — the same reduction `extend.rs` uses. Keeping the pairs of the
//! current family in buckets indexed by `A ∩ B`, a candidate `x` is
//! tested by looking up the `2^b` subsets of `x` and checking `x ∩ Δ = ∅`
//! for the pairs found. At `b = 6` that is 64 lookups into buckets
//! averaging four entries, against the 50000 pairs a naive scan would
//! walk.
//!
//! ## What a negative result here is worth
//!
//! Exhausting a group is a real statement — "no `G`-invariant family of
//! 317 exists" — provided the budget is reported. Every run below
//! records whether it finished, and the caller is expected to say so.

use std::collections::HashMap;
use std::hash::{BuildHasherDefault, Hasher};

/// A multiply-shift hasher for `u64` keys. The default `SipHash` costs
/// more than the bucket lookups it guards -- `can_add` does `2^b` of
/// them per candidate, and at `b = 6` that is the inner loop of the
/// whole search.
#[derive(Default)]
pub struct FastHasher(u64);

impl Hasher for FastHasher {
    fn finish(&self) -> u64 {
        self.0
    }
    fn write(&mut self, bytes: &[u8]) {
        for &b in bytes {
            self.0 = (self.0 ^ u64::from(b)).wrapping_mul(0x100_0000_01b3);
        }
    }
    fn write_u64(&mut self, n: u64) {
        // splitmix64 finaliser
        let mut z = n.wrapping_add(0x9e37_79b9_7f4a_7c15);
        z = (z ^ (z >> 30)).wrapping_mul(0xbf58_476d_1ce4_e5b9);
        z = (z ^ (z >> 27)).wrapping_mul(0x94d0_49bb_1331_11eb);
        self.0 = z ^ (z >> 31);
    }
}

type FastMap<K, V> = HashMap<K, V, BuildHasherDefault<FastHasher>>;

/// A permutation of `[n]`, as the list of images.
pub type Perm = Vec<u32>;

/// The image of a subset under a permutation.
#[inline]
pub fn apply(p: &Perm, set: u64) -> u64 {
    let mut out = 0u64;
    let mut m = set;
    while m != 0 {
        let bit = m.trailing_zeros();
        m &= m - 1;
        out |= 1u64 << p[bit as usize];
    }
    out
}

fn compose(p: &Perm, q: &Perm) -> Perm {
    q.iter().map(|&x| p[x as usize]).collect()
}

/// Every element of the group generated by `gens`, by closure. Returns
/// `None` if the group exceeds `cap` — a prescribed group that large is
/// not one this search wants.
pub fn group_closure(n: u32, gens: &[Perm], cap: usize) -> Option<Vec<Perm>> {
    let identity: Perm = (0..n).collect();
    let mut seen: Vec<Perm> = vec![identity.clone()];
    let mut frontier: Vec<Perm> = vec![identity];
    while let Some(p) = frontier.pop() {
        for g in gens {
            let q = compose(g, &p);
            if !seen.contains(&q) {
                if seen.len() >= cap {
                    return None;
                }
                seen.push(q.clone());
                frontier.push(q);
            }
        }
    }
    seen.sort();
    Some(seen)
}

/// The orbits of `group` on the `b`-subsets of `[n]`, each sorted.
pub fn orbits_on_subsets(n: u32, b: u32, group: &[Perm]) -> Vec<Vec<u64>> {
    let mut seen: HashMap<u64, ()> = HashMap::new();
    let mut out = Vec::new();
    let mut cur = 0u64;
    fn rec(n: u32, b: u32, start: u32, cur: &mut u64, depth: u32, all: &mut Vec<u64>) {
        if depth == b {
            all.push(*cur);
            return;
        }
        for x in start..n {
            *cur |= 1u64 << x;
            rec(n, b, x + 1, cur, depth + 1, all);
            *cur &= !(1u64 << x);
        }
    }
    let mut all = Vec::new();
    rec(n, b, 0, &mut cur, 0, &mut all);
    for s in all {
        if seen.contains_key(&s) {
            continue;
        }
        let mut orb: Vec<u64> = group.iter().map(|p| apply(p, s)).collect();
        orb.sort_unstable();
        orb.dedup();
        for &t in &orb {
            seen.insert(t, ());
        }
        out.push(orb);
    }
    out
}

/// A family under construction, with the machinery to add and undo a
/// member in time proportional to its size rather than its square.
///
/// `buckets[I]` holds the symmetric differences of the pairs whose
/// intersection is `I`. A candidate `x` completes a sunflower with some
/// pair exactly when one of those buckets, indexed by a subset of `x`,
/// contains a `Δ` disjoint from `x`.
pub struct Incremental {
    pub members: Vec<u64>,
    buckets: FastMap<u64, Vec<u64>>,
    /// The bucket key of every pair inserted, in insertion order, so an
    /// undo is a sequence of pops.
    trail: Vec<u64>,
    /// How many trail entries each member added.
    marks: Vec<usize>,
    intersecting: bool,
}

impl Incremental {
    pub fn new(intersecting: bool) -> Self {
        Incremental {
            members: Vec::new(),
            buckets: FastMap::default(),
            trail: Vec::new(),
            marks: Vec::new(),
            intersecting,
        }
    }

    pub fn len(&self) -> usize {
        self.members.len()
    }

    pub fn is_empty(&self) -> bool {
        self.members.is_empty()
    }

    /// May `x` be added: distinct, meeting everything (when asked), and
    /// completing no 3-sunflower?
    pub fn can_add(&self, x: u64) -> bool {
        for &a in &self.members {
            if a == x {
                return false;
            }
            if self.intersecting && a & x == 0 {
                return false;
            }
        }
        // Every subset of `x` is a possible pair-intersection, and the
        // standard `(sub - 1) & x` walk enumerates them as masks with no
        // allocation -- which matters, because this is the inner loop.
        let mut sub = x;
        loop {
            if let Some(deltas) = self.buckets.get(&sub) {
                for &d in deltas {
                    if d & x == 0 {
                        return false;
                    }
                }
            }
            if sub == 0 {
                break;
            }
            sub = (sub - 1) & x;
        }
        true
    }

    pub fn push(&mut self, x: u64) {
        let before = self.trail.len();
        for &a in &self.members {
            let key = a & x;
            let delta = a ^ x;
            self.buckets.entry(key).or_default().push(delta);
            self.trail.push(key);
        }
        self.marks.push(self.trail.len() - before);
        self.members.push(x);
    }

    pub fn pop(&mut self) {
        let k = self.marks.pop().expect("pop on an empty family");
        for _ in 0..k {
            let key = self.trail.pop().expect("trail underflow");
            let v = self.buckets.get_mut(&key).expect("bucket vanished");
            v.pop();
            if v.is_empty() {
                self.buckets.remove(&key);
            }
        }
        self.members.pop();
    }

    /// Add a whole orbit, or restore the family and report failure.
    pub fn push_orbit(&mut self, orb: &[u64]) -> bool {
        let mut added = 0;
        for &x in orb {
            if self.can_add(x) {
                self.push(x);
                added += 1;
            } else {
                for _ in 0..added {
                    self.pop();
                }
                return false;
            }
        }
        true
    }

    pub fn pop_orbit(&mut self, orb: &[u64]) {
        for _ in 0..orb.len() {
            self.pop();
        }
    }
}

/// The result of one prescribed-group search.
#[derive(Debug, Clone)]
pub struct OrbitResult {
    pub best: usize,
    pub best_family: Vec<u64>,
    pub nodes: u64,
    pub exhaustive: bool,
}

/// Search the unions of orbits for a family of at least `target`
/// members, intersecting (when asked) and 3-sunflower-free.
///
/// Orbits are tried in a fixed order and each is either taken whole or
/// skipped, which is what makes the search a search over `G`-invariant
/// families rather than over families. The bound is the usual one — what
/// is in hand plus everything still to come — and it is what makes an
/// exhausted run mean something: no union of these orbits reaches the
/// target.
pub fn search_orbits(
    orbits: &[Vec<u64>],
    target: usize,
    intersecting: bool,
    budget: u64,
) -> OrbitResult {
    // Largest orbits first: the bound bites sooner, and an orbit that is
    // inconsistent with itself is discovered at the root rather than at
    // a leaf.
    let mut ord: Vec<usize> = (0..orbits.len()).collect();
    ord.sort_by_key(|&i| std::cmp::Reverse(orbits[i].len()));

    struct S<'a> {
        orbits: &'a [Vec<u64>],
        target: usize,
        nodes: u64,
        budget: u64,
        best: usize,
        best_family: Vec<u64>,
        done: bool,
    }

    // The candidate list carries only the orbits still addable, and
    // "addable" is monotone -- once a member of an orbit clashes with the
    // family it clashes with every extension of it -- so filtering is
    // sound and never has to be undone. This is the max-clique shape,
    // not a subset walk: the loop over `cands` covers "skip this orbit"
    // implicitly, so there is no exponential branch on skipping.
    fn rec(s: &mut S, fam: &mut Incremental, cands: &[usize]) {
        s.nodes += 1;
        if s.nodes > s.budget {
            return;
        }
        if fam.len() > s.best {
            s.best = fam.len();
            s.best_family = fam.members.clone();
        }
        if fam.len() >= s.target {
            s.done = true;
            return;
        }
        let mut rest: usize = cands.iter().map(|&i| s.orbits[i].len()).sum();
        for idx in 0..cands.len() {
            if fam.len() + rest < s.target {
                return;
            }
            let o = cands[idx];
            rest -= s.orbits[o].len();
            if !fam.push_orbit(&s.orbits[o]) {
                continue;
            }
            let next: Vec<usize> = cands[idx + 1..]
                .iter()
                .copied()
                .filter(|&j| s.orbits[j].iter().all(|&x| fam.can_add(x)))
                .collect();
            rec(s, fam, &next);
            if s.done || s.nodes > s.budget {
                return;
            }
            fam.pop_orbit(&s.orbits[o]);
        }
    }

    let mut st = S {
        orbits,
        target,
        nodes: 0,
        budget,
        best: 0,
        best_family: Vec::new(),
        done: false,
    };
    let mut fam = Incremental::new(intersecting);
    rec(&mut st, &mut fam, &ord);
    OrbitResult {
        best: st.best,
        best_family: st.best_family,
        nodes: st.nodes,
        exhaustive: st.nodes <= st.budget,
    }
}

/// Verify a family from scratch: `b`-uniform, distinct, sunflower-free,
/// and optionally intersecting. Shares no code with the search.
pub fn verify(f: &[u64], b: u32, intersecting: bool) -> Result<(), String> {
    for (i, a) in f.iter().enumerate() {
        if a.count_ones() != b {
            return Err(format!("member {i} has size {}", a.count_ones()));
        }
        for (j, y) in f.iter().enumerate().skip(i + 1) {
            if a == y {
                return Err(format!("members {i} and {j} are equal"));
            }
            if intersecting && a & y == 0 {
                return Err(format!("members {i} and {j} are disjoint"));
            }
            let ab = a & y;
            for (l, c) in f.iter().enumerate().skip(j + 1) {
                if ab == (a & c) && ab == (y & c) {
                    return Err(format!("members {i},{j},{l} are a 3-sunflower"));
                }
            }
        }
    }
    Ok(())
}

