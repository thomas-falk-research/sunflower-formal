(** * Link size 23–27 in the kernel, and the descent from 23

    The 14,805 link classes of size 23–27 ([classes_23_27.txt.gz]) each carry
    a certificate checked by [LPCert.check] through [Link23.lpclass], in
    11 modules ([Link23s0] to [Link23s10]).  Each module exports its
    class list and proves every class [CheckedClass]; the certificates stay
    inside that opaque proof.  This gives
    the descent at 23 and [g(4) ≤ 78], conditional on
    [ι(4) ≤ 27] and on the census being complete from 23 up
    ([CensusL classes23 23]).  Generated by tools/iota4/lpcombine.py;
    see docs/roadmap.md §73. *)

From Coq Require Import List Lia.
Import ListNotations.
From Sunflower Require Import Sunflower IotaRate LinkCombine Link23
  Link23s0 Link23s1 Link23s2 Link23s3 Link23s4 Link23s5 Link23s6 Link23s7 Link23s8 Link23s9 Link23s10.

(** Every certified link class of size 23 to 27. *)
Definition classes23 : list Family :=
  l23s0_classes ++
  l23s1_classes ++
  l23s2_classes ++
  l23s3_classes ++
  l23s4_classes ++
  l23s5_classes ++
  l23s6_classes ++
  l23s7_classes ++
  l23s8_classes ++
  l23s9_classes ++
  l23s10_classes.

Lemma classes23_checked : forall D, In D classes23 -> CheckedClass D.
Proof.
  unfold classes23.
  apply checked_app; [exact l23s0_ok |].
  apply checked_app; [exact l23s1_ok |].
  apply checked_app; [exact l23s2_ok |].
  apply checked_app; [exact l23s3_ok |].
  apply checked_app; [exact l23s4_ok |].
  apply checked_app; [exact l23s5_ok |].
  apply checked_app; [exact l23s6_ok |].
  apply checked_app; [exact l23s7_ok |].
  apply checked_app; [exact l23s8_ok |].
  apply checked_app; [exact l23s9_ok |].
  exact l23s10_ok.
Qed.

(** The descent at link size 23 and above. *)
Theorem descent_23 :
  IotaAtMost 4 27 -> CensusL classes23 23 -> LinkDescent 4 23 54.
Proof. intros Hi Hc; exact (descent_of_censusL Hi classes23 23 ltac:(lia) classes23_checked Hc). Qed.

Theorem g_four_at_most_78_of_census_23 :
  IotaAtMost 4 27 -> CensusL classes23 23 -> MeetingBound 4 56 -> GAtMost 4 78.
Proof.
  intros Hi Hc Hm.
  pose proof (g_at_most_of_descent_and_meeting 4 23 54 56 (descent_23 Hi Hc) Hm) as H.
  replace (Nat.max 54 (23 - 1 + 56)) with 78 in H by reflexivity. exact H.
Qed.
