#!/usr/bin/env python3
"""The combining modules coq/Link23Certs.v, coq/Link22Certs.v and
coq/Link21Certs.v over the certificate modules written by
`link23_coq.py lpshards` (docs/roadmap.md §73).

  lpcombine.py N23 N22 N21

N23, N22, N21: the number of modules Link23s*, Link22s*, Link21s*.  Each
combining module lists the classes of its size and above, proves every one
[CheckedClass] from the modules' opaque lemmas, and states the descent and
the bound on g(4) under [CensusL] for that list.
"""
import sys

HEAD = ["From Coq Require Import List Lia.", "Import ListNotations."]

LEVELS = {
    23: dict(prev=None, count="14,805", file="classes_23_27.txt.gz", sizes="23–27", g=78),
    22: dict(prev=23, count="69,616", file="classes_22.txt.gz", sizes="22", g=77),
    21: dict(prev=22, count="407,115", file="classes_21.txt.gz", sizes="21", g=76),
}


def module(size, n):
    L = LEVELS[size]
    mods = [f"Link{size}s{i}" for i in range(n)]
    prev = L["prev"]
    lines = [
        f"(** * Link size {L['sizes']} in the kernel, and the descent from {size}",
        "",
        f"    The {L['count']} link classes of size {L['sizes']} ([{L['file']}]) each carry",
        "    a certificate checked by [LPCert.check] through [Link23.lpclass], in",
        f"    {n} modules ([Link{size}s0] to [Link{size}s{n - 1}]).  Each module exports its",
        "    class list and proves every class [CheckedClass]; the certificates stay",
        "    inside that opaque proof." + ("  This gives" if prev is None else
        f"  With the classes of sizes {prev} and up ([Link{prev}Certs.classes{prev}])"),
        ("    " if prev is None else "    this gives ") + f"the descent at {size} and [g(4) ≤ {L['g']}], conditional on",
        f"    [ι(4) ≤ 27] and on the census being complete from {size} up",
        f"    ([CensusL classes{size} {size}]).  Generated by tools/iota4/lpcombine.py;",
        "    see docs/roadmap.md §73. *)",
        "",
    ] + HEAD + [
        "From Sunflower Require Import Sunflower IotaRate LinkCombine Link23"
        + ("" if prev is None else f" Link{prev}Certs"),
        "  " + " ".join(mods) + ".",
        "",
        f"(** Every certified link class of size {size} to 27. *)",
        f"Definition classes{size} : list Family :=",
    ]
    parts = ([] if prev is None else [f"classes{prev}"]) + [f"l{size}s{i}_classes" for i in range(n)]
    lines.append("  " + " ++\n  ".join(parts) + ".")
    lines += ["", f"Lemma classes{size}_checked : forall D, In D classes{size} -> CheckedClass D.",
              "Proof.", f"  unfold classes{size}."]
    oks = ([] if prev is None else [f"classes{prev}_checked"]) + [f"l{size}s{i}_ok" for i in range(n)]
    for o in oks[:-1]:
        lines.append(f"  apply checked_app; [exact {o} |].")
    lines.append(f"  exact {oks[-1]}.")
    lines += ["Qed.", "",
              f"(** The descent at link size {size} and above. *)",
              f"Theorem descent_{size} :",
              f"  IotaAtMost 4 27 -> CensusL classes{size} {size} -> LinkDescent 4 {size} 54.",
              f"Proof. intros Hi Hc; exact (descent_of_censusL Hi classes{size} {size} ltac:(lia) classes{size}_checked Hc). Qed.",
              "",
              f"Theorem g_four_at_most_{L['g']}_of_census_{size} :",
              f"  IotaAtMost 4 27 -> CensusL classes{size} {size} -> MeetingBound 4 56 -> GAtMost 4 {L['g']}.",
              "Proof.",
              "  intros Hi Hc Hm.",
              f"  pose proof (g_at_most_of_descent_and_meeting 4 {size} 54 56 (descent_{size} Hi Hc) Hm) as H.",
              f"  replace (Nat.max 54 ({size} - 1 + 56)) with {L['g']} in H by reflexivity. exact H.",
              "Qed.", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    n23, n22, n21 = map(int, sys.argv[1:4])
    for size, n in ((23, n23), (22, n22), (21, n21)):
        open(f"coq/Link{size}Certs.v", "w").write(module(size, n))
        print(f"wrote coq/Link{size}Certs.v over {n} modules")
