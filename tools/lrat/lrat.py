#!/usr/bin/env python3
"""LRAT proofs of unsatisfiability, checked in Coq's kernel by coq/LRAT.v.

  lrat.py check CNF LRAT            the Coq semantics, in Python
  lrat.py coq   CNF LRAT OUT.v NAME a Coq module proving the CNF unsatisfiable

CNF is DIMACS; LRAT is the textual format CaDiCaL writes with
`--lrat=true --binary=false`:

  id lit ... 0 hint ... 0     add clause [id] by reverse unit propagation
  id d id ... 0               delete clauses

Only reverse-unit-propagation steps are supported: a negative hint (a RAT
step) is refused when parsing.  The Python checker is a second
implementation for convenience; the trusted check is Coq's
`LRAT.lrat_check`, decided by `vm_compute`.
"""
import sys


class CertError(Exception):
    pass


def parse_dimacs(path):
    clauses, cur = [], []
    for line in open(path):
        t = line.split()
        if not t or t[0] in ("c", "p", "%"):
            continue
        for x in t:
            v = int(x)
            if v == 0:
                clauses.append(cur); cur = []
            else:
                cur.append(v)
    if cur:
        raise CertError("unterminated clause in the CNF")
    return clauses


def parse_lrat(path):
    """[("a", id, lits, hints) | ("d", ids)]"""
    steps = []
    for n, line in enumerate(open(path), 1):
        t = line.split()
        if not t or t[0] == "c":
            continue
        i = int(t[0])
        if len(t) > 1 and t[1] == "d":
            ids = [int(x) for x in t[2:]]
            if not ids or ids[-1] != 0:
                raise CertError("line %d: deletion not terminated" % n)
            steps.append(("d", ids[:-1]))
            continue
        nums = [int(x) for x in t[1:]]
        if nums.count(0) != 2 or nums[-1] != 0:
            raise CertError("line %d: expected 'id lits 0 hints 0'" % n)
        k = nums.index(0)
        lits, hints = nums[:k], nums[k + 1:-1]
        if any(h <= 0 for h in hints):
            raise CertError("line %d: RAT step (negative hint) not supported" % n)
        steps.append(("a", i, lits, hints))
    return steps


# ---------------------------------------------------------------- the checker (LRAT.v)

def _aval(a, l):
    if l > 0:
        return a.get(l)
    if l < 0:
        v = a.get(-l)
        return None if v is None else (not v)
    return False


def _aset(a, l):
    v = _aval(a, l)
    if v is True:
        return a
    if v is False:
        return None
    b = dict(a); b[abs(l)] = l > 0
    return b


def rup(db, C, hints):
    if any(l == 0 for l in C):
        return False
    a = {}
    for l in C:
        a = _aset(a, -l)
        if a is None:
            return True                      # a tautology
    for h in hints:
        D = db.get(h)
        if D is None:
            return False
        unit, ok = None, True
        for l in D:
            v = _aval(a, l)
            if v is False:
                continue
            if v is True or unit is not None:
                ok = False; break
            unit = l
        if not ok:
            return False
        if unit is None:
            return True                      # conflict
        a2 = _aset(a, unit)
        if a2 is None:
            return False
        a = a2
    return False


def check(cnf, steps):
    db = {i + 1: C for i, C in enumerate(cnf)}
    for s in steps:
        if s[0] == "a":
            _, i, C, hints = s
            if not rup(db, C, hints):
                return False
            if not C:
                return True
            db[i] = C
        else:
            for i in s[1]:
                db.pop(i, None)
    return False


# ---------------------------------------------------------------- Coq output

def _zl(xs):
    return "[" + "; ".join(str(x) for x in xs) + "]"


def to_coq(cnf, steps, name):
    st = []
    for s in steps:
        st.append(f"A {s[1]} {_zl(s[2])} {_zl(s[3])}" if s[0] == "a" else f"D {_zl(s[1])}")
    return "\n".join([
        "(* Generated by tools/lrat/lrat.py; do not edit. *)",
        "From Coq Require Import ZArith List.", "Import ListNotations.",
        "From Sunflower Require Import LRAT.", "Local Open Scope Z_scope.", "",
        f"Definition {name}_cnf : list clause :=\n  [" + ";\n   ".join(_zl(C) for C in cnf) + "].",
        f"Definition {name}_proof : list step :=\n  [" + ";\n   ".join(st) + "].", "",
        f"Lemma {name}_ok : lrat_check {name}_cnf {name}_proof = true.",
        "Proof. vm_compute. reflexivity. Qed.", "",
        f"Theorem {name}_unsat : forall v, cnf_sat v {name}_cnf = false.",
        f"Proof. exact (lrat_sound {name}_cnf {name}_proof {name}_ok). Qed.", ""])


if __name__ == "__main__":
    mode = sys.argv[1]
    cnf, steps = parse_dimacs(sys.argv[2]), parse_lrat(sys.argv[3])
    if mode == "check":
        ok = check(cnf, steps)
        print("CHECK PASS" if ok else "CHECK FAIL"); sys.exit(0 if ok else 1)
    if mode == "coq":
        open(sys.argv[4], "w").write(to_coq(cnf, steps, sys.argv[5]))
